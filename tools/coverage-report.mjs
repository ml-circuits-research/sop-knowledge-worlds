// The coverage report (Round 8, item 6): for the 1,500 common things of tools/coverage.mjs, how many have a
// drawing, a stand-in, a place, a size, a colour, parts and the other attributes, and in how many of them each
// world has anything to say; and the most frequent things that lack each. The gaps drive the next round.
//   node tools/coverage-report.mjs     writes docs/worlds/COVERAGE.md (needs the raw files of
//                                      sources/wordnet/SOURCE.md and sources/frequency-words/SOURCE.md; run
//                                      tools/build-catalog.mjs before it, for vocab.json, and after it)
// A thing is counted "by its name" when a fact is named by the word itself, and "through its drawing" when the
// fact is named by its drawing or by the drawing it reaches through a synonym or a stand-in.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { WORLDS_DIR } from './lib/worlds.mjs';
import { run } from './coverage.mjs';
import { factsByType } from './aspects-report.mjs';

const tok = (t) => (t?.startsWith('"') ? JSON.parse(t) : t);
export const COVERAGE_PAGE = join(WORLDS_DIR, 'COVERAGE.md');
const GAP = 30;
// Attributes that only some kinds of things have: no list of gaps is printed for them.
const SOME_KINDS = new Set(['wheels', 'legs', 'where it is worn']);

// What is counted: [label, [type, the key that names the thing, the keys that count (any of them)] ...].
export const ROWS = [
  ['place', ['k.scenes.thing', 'name', ['place']]],
  ['size', ['k.scenes.thing', 'name', ['size']]],
  ['colour (usual colour of the thing)', ['k.attributes.thing', 'name', ['colour']], ['k.food.food', 'name', ['colour']]],
  ['colour of the parts of a drawing', ['k.objects.part', 'of', ['colour']]],
  ['parts (WordNet, own or inherited)', ['k.parts.whole', 'name', ['has']], ['k.parts.inherited', 'name', ['has']]],
  ['parts (named parts of a drawing)', ['k.objects.part', 'of', ['name'], (w) => !/^part\d+$/.test(tok(w.attrs.name?.[0] ?? 'part0'))]],
  ['parts or joins between kinds', ['k.layouts.joins', 'b', ['a']]],
  ['anchor (where another thing sits)', ['k.layouts.anchor', 'of', ['kind']]],
  ['material', ['k.attributes.thing', 'name', ['material']], ['k.commonsense.thing', 'name', ['made_of']]],
  ['what it can do', ['k.attributes.thing', 'name', ['can']], ['k.animals.animal', 'name', ['can']], ['k.commonsense.thing', 'name', ['can']]],
  ['what it is used for', ['k.attributes.thing', 'name', ['used_for']], ['k.commonsense.thing', 'name', ['used_for']]],
  ['wheels', ['k.attributes.thing', 'name', ['wheels']]],
  ['legs', ['k.animals.animal', 'name', ['legs']]],
  ['kind (what it is a kind of)', ['k.words.sense', 'word', ['is_a']]],
  ['definition', ['k.words.sense', 'word', ['gloss']]],
  ['where it is worn', ['k.wearables.wearable', 'name', ['worn_on']]],
];

export function coverageReport(list, vocab) {
  const facts = factsByType(ROWS.flatMap((r) => r.slice(1).map((s) => s[0])));
  const sets = (row) => row.slice(1).map(([type, by, keys, only]) => new Set(facts.get(type).filter((w) => keys.some((k) => w.attrs[k]) && (!only || only(w))).flatMap((w) => (w.attrs[by] ?? []).map((t) => tok(t).toLowerCase()))));
  const drawn = list.filter((e) => e.drawing), linked = list.filter((e) => !e.drawing && e.link), neither = list.filter((e) => !e.drawing && !e.link);
  const rows = ROWS.map((row) => {
    const ss = sets(row);
    const has = (n) => n && ss.some((s) => s.has(n.toLowerCase()));
    const own = list.filter((e) => has(e.word));
    const through = list.filter((e) => !has(e.word) && (has(e.drawing) || has(e.link?.drawing)));
    const none = list.filter((e) => !has(e.word) && !has(e.drawing) && !has(e.link?.drawing));
    return { label: row[0], where: row.slice(1).map(([type, , keys]) => `\`${type}\` (${keys.join(', ')})`).join(', '), own: own.length, through: through.length, none: none.length, gap: none.slice(0, GAP).map((e) => e.word) };
  });
  const worlds = new Map();
  for (const e of list) for (const w of new Set((vocab[e.word] ?? []).map((id) => id.split('/')[0]))) worlds.set(w, (worlds.get(w) ?? 0) + 1);
  return { total: list.length, drawn: drawn.length, linked: linked.length, neither: neither.length, neitherGap: neither.slice(0, GAP).map((e) => e.word), rows, worlds: [...worlds.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1)) };
}

export function coveragePage(r) {
  const pct = (n) => `${n} (${Math.round((100 * n) / r.total)}%)`;
  const lines = ['# Coverage of the common things', '',
    'Generated by `tools/coverage-report.mjs`; do not edit by hand. The common things are the 1,500 most frequent',
    'English nouns that name a physical thing (the list of `tools/coverage.mjs`, see `k.objects/MISSING.md`).',
    '"By its name": a fact is named by the word itself. "Through its drawing": the fact is named by the drawing of',
    'the word, or by the drawing it reaches through a synonym or a stand-in (a puppy is drawn by the dog, so it has',
    'the place of the dog).', '',
    '## Drawings', '',
    `- a drawing of its own name: ${pct(r.drawn)}`, `- no drawing, but a synonym or a stand-in with one: ${pct(r.linked)}`, `- neither: ${pct(r.neither)}`,
    `- the most frequent with neither: ${r.neitherGap.join(', ')}`, '',
    '## Attributes', '', '| attribute | by its name | through its drawing | none | where |', '|---|---:|---:|---:|---|'];
  for (const x of r.rows) lines.push(`| ${x.label} | ${pct(x.own)} | ${pct(x.through)} | ${pct(x.none)} | ${x.where} |`);
  lines.push('', '## Worlds', '', 'How many of the common things are a word of the vocabulary index that leads to a shard of the world.', '', '| world | common things |', '|---|---:|');
  for (const [w, n] of r.worlds) lines.push(`| \`${w}\` | ${pct(n)} |`);
  lines.push('', '## Gaps', '', `The ${GAP} most frequent common things with no value, by their name or through a drawing.`, '');
  lines.push('A missing value is not always a gap: many things have no usual colour (a car, a door), and wheels, legs and', 'the place where a thing is worn belong to some kinds of things only (no list for those).', '');
  for (const x of r.rows) if (x.none && !SOME_KINDS.has(x.label)) lines.push(`- **${x.label}**: ${x.gap.join(', ')}`);
  return `${lines.join('\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const vocab = JSON.parse(readFileSync(join(WORLDS_DIR, 'vocab.json'), 'utf8'));
  const report = coverageReport(run().list, vocab);
  writeFileSync(COVERAGE_PAGE, coveragePage(report));
  console.log(`drawing ${report.drawn}, synonym or stand-in ${report.linked}, neither ${report.neither}`);
  for (const x of report.rows) console.log(`${x.label}: ${x.own} + ${x.through}, none ${x.none}`);
}
