// The coverage table "family of things x aspect" (reviewer, 2026-11-13 21:30): for each family of
// k.attributes.family and each aspect, how many things of the family have at least one value of the aspect, counted
// from the shards through the k.attributes.shows rows (tools/attributes-core.mjs).
//   node tools/aspects-report.mjs      writes docs/worlds/k.attributes/ASPECTS.md
// The family "common thing" is the list of tools/coverage.mjs, which needs the raw WordNet and frequency files
// (sources/wordnet/SOURCE.md, sources/frequency-words/SOURCE.md). A common thing is looked up by its word, by the
// name of its drawing, and by the drawing it reaches through a synonym or a stand-in.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from './sopworld/sopworld.mjs';
import { WORLDS_DIR, scanWorlds } from './lib/worlds.mjs';
import { ASPECTS, FAMILIES, SHOWS } from './attributes-core.mjs';
import { run } from './coverage.mjs';

const tok = (t) => (t?.startsWith('"') ? JSON.parse(t) : t);
export const ASPECTS_PAGE = join(WORLDS_DIR, 'k.attributes', 'ASPECTS.md');

// type -> its facts, for the types the rows name (parsed once from the shards of their worlds).
export function factsByType(types) {
  const wanted = new Set(types);
  const worlds = new Set([...wanted].map((t) => t.split('.').slice(0, 2).join('.')));
  const out = new Map([...wanted].map((t) => [t, []]));
  for (const world of scanWorlds()) {
    if (!worlds.has(world.id)) continue;
    for (const shard of world.shards) for (const w of parse(shard.text)) if (wanted.has(w.type)) out.get(w.type).push(w);
  }
  return out;
}

// The names a common thing is looked up by.
export const namesOf = (entry) => [...new Set([entry.word, entry.drawing, entry.link?.drawing].filter(Boolean).map((n) => n.toLowerCase()))];

export function aspectTable(commonList) {
  const facts = factsByType([...SHOWS.map((r) => r.type), ...FAMILIES.map((f) => f[3]).filter(Boolean)]);
  // (type, by, key) -> the set of thing names (lower case) that have a value.
  const have = new Map();
  const namesWith = (type, by, key) => {
    const id = `${type} ${by} ${key}`;
    if (!have.has(id)) have.set(id, new Set(facts.get(type).filter((w) => w.attrs[key]).flatMap((w) => (w.attrs[by] ?? []).map((t) => tok(t).toLowerCase()))));
    return have.get(id);
  };
  const rows = [];
  for (const [family, , , type, by] of FAMILIES) {
    const things = type ? [...new Set(facts.get(type).flatMap((w) => (w.attrs[by] ?? []).map((t) => tok(t).toLowerCase())))].map((n) => [n]) : commonList.map(namesOf);
    const cells = ASPECTS.map(([aspect]) => {
      const sets = SHOWS.filter((r) => r.family === family && r.aspect === aspect).flatMap((r) => r.keys.map((k) => namesWith(r.type, r.by, k)));
      return sets.length ? things.filter((names) => names.some((n) => sets.some((s) => s.has(n)))).length : null;
    });
    rows.push({ family, total: things.length, cells });
  }
  return rows;
}

export function aspectsPage(rows) {
  const pct = (n, total) => (total ? `${n} (${Math.round((100 * n) / total)}%)` : `${n}`);
  const lines = ['# Families of things and their aspects', '',
    'Generated by `tools/aspects-report.mjs` from the shards and the `k.attributes.shows` facts; do not edit by hand.',
    'A cell says how many things of the family have at least one value of the aspect; a dash says that no world',
    'holds values of that aspect for the family. Where the values are (world, type, key) is in the shard',
    '`k.attributes/shards/aspects`. A common thing is counted when its word, its drawing or the drawing it reaches',
    'through a synonym or a stand-in has the value.', '',
    `| family | things | ${ASPECTS.map((a) => a[0]).join(' | ')} |`, `|---|---:|${ASPECTS.map(() => '---:').join('|')}|`];
  for (const r of rows) lines.push(`| ${r.family} | ${r.total} | ${r.cells.map((c) => (c === null ? '–' : pct(c, r.total))).join(' | ')} |`);
  lines.push('', '## Where the values are', '');
  for (const [family] of FAMILIES) {
    lines.push(`- **${family}**: ${ASPECTS.map(([aspect]) => { const rs = SHOWS.filter((r) => r.family === family && r.aspect === aspect); return rs.length ? `${aspect}: ${rs.map((r) => `\`${r.type}\` (${r.keys.join(', ')})`).join(', ')}` : null; }).filter(Boolean).join('; ')}.`);
  }
  return `${lines.join('\n')}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const rows = aspectTable(run().list);
  writeFileSync(ASPECTS_PAGE, aspectsPage(rows));
  for (const r of rows) console.log(r.family, r.total, r.cells.map((c) => c ?? '-').join(' '));
}
