// Scans docs/worlds, validates every world, and writes docs/worlds/index.json (the catalog, PLAN.md §2) and
// docs/worlds/vocab.json (English lemma -> shard ids), docs/worlds/vocab-kinds.json (English lemma -> the kind of
// thing or key it names -> shard ids) and docs/worlds/LICENSES.md (the terms and attribution texts of
// every source, from sources/<id>/SOURCE.md). Deterministic: sorted, no dates; a rerun gives no diff.
//   node tools/build-catalog.mjs [worlds-dir]      write the files
//   node tools/build-catalog.mjs --check           exit 1 when the files on disk are not what a build gives
import { worldOfWordsShard } from './lib/words-shards.mjs';
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { dataFolders } from './lib/licenses.mjs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { parse, str } from './sopworld/sopworld.mjs';
import { validateWorlds } from './validate.mjs';
import { readHeader, moduleInfo, schemaWorld, WORLDS_DIR, REPO } from './lib/worlds.mjs';
import { scanSchemas, describeSchema } from './lib/schemas.mjs';

const byText = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const uniqSorted = (xs) => [...new Set(xs)].sort(byText);
const SOPWORLD = /commit: (\w{7})/.exec(readFileSync(join(REPO, 'tools/sopworld/VERSION'), 'utf8'))[1];
const GENERATED = new Set(['index.json', 'vocab.json', 'vocab-kinds.json', 'LICENSES.md']);

// A value token as plain text: strings unquoted; references and variables are not words.
const text = (token) => (token.startsWith('"') ? str(token) : /^[$?]/.test(token) ? null : token);
// Names that stand for "not named yet" (part1, part2, ... of an imported drawing) are not words.
const PLACEHOLDER = /^part\d+$/;
const WORD_KEYS = new Set(['text', 'singular', 'ending']);
// Block 07:40 item 4: keys of a knowledge world whose values name things of other worlds (the typical things of a
// shape or a colour, the thing placed somewhere): a word for such a thing also leads to the fact ("what shape is a
// stop sign" reaches the octagon). The kind is the key (k.shapes.shape.thing).
const THING_KEYS = new Set(['thing']);
// Q67 (b): the key of a type that holds search words (k.objects.keyword: the tags of an image library). A keyword
// still leads to its shard, with the type as its kind, but after the shards that have the word as a name or a word.
const SEARCH_KEYS = new Map([['k.objects.keyword', 'text']]);
const isWordy = (t) => t && /\p{L}/u.test(t);
const lemma = (t) => t.toLowerCase();
const sourceId = (s) => text(s).trim().split(/\s+/).join('-');

// The catalog version: a content hash of every published world file (not of the generated files).
function contentVersion(root) {
  const files = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort(byText)) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (!(dir === root && GENERATED.has(name))) files.push(p);
    }
  };
  walk(root);
  const h = createHash('sha256');
  for (const f of files) h.update(relative(root, f).split('\\').join('/')).update('\0').update(readFileSync(f)).update('\0');
  return h.digest('hex').slice(0, 12);
}

// The "- **Key:** text" lines of a SOURCE.md (a line continues on the indented lines after it).
export function readSource(textOfFile) {
  const out = {};
  let key = null;
  for (const line of textOfFile.split('\n')) {
    const m = /^- \*\*([^*:]+):\*\*\s*(.*)$/.exec(line);
    if (m) { key = m[1].trim().toLowerCase(); out[key] = m[2].trim(); }
    else if (key && /^\s+\S/.test(line)) out[key] += ` ${line.trim()}`;
    else key = null;
  }
  return out;
}

// LICENSES.md: per source used by a published shard, its terms and attribution, and the shards that carry them.
function licensesText(index, sourcesDir) {
  const bySource = new Map();
  // the shards and the folders of data files (KR1 item 6: the TSV dictionaries, counted as one entry per file)
  for (const w of index.worlds) for (const s of [...w.shards, ...(w.data ?? []).flatMap((d) => Array.from({ length: d.files }, () => ({ ...d, id: `${d.id}/` })))]) for (const src of s.sources) {
    if (!bySource.has(src)) bySource.set(src, { shards: [], licenses: new Set() });
    bySource.get(src).shards.push(s);
    if (s.license) bySource.get(src).licenses.add(s.license);
  }
  const dirs = existsSync(sourcesDir) ? readdirSync(sourcesDir).sort(byText).reverse() : [];
  const lines = ['# Licenses and attribution', '',
    'Generated by `tools/build-catalog.mjs` from the shard headers and `sources/<id>/SOURCE.md`; do not edit by hand.',
    'A shard keeps the terms of its sources: share-alike stays share-alike, in shards (and folders of data files) of its',
    'own. Non-commercial, no-derivatives, research-only and unknown terms are never imported; `tools/validate.mjs` refuses',
    'any licence outside its allowlist (`tools/lib/licenses.mjs`). The schemas are written in this repository (source',
    '`hand-core`). "Shards" below counts SOP shards and the files of the TSV dictionaries.', ''];
  for (const src of [...bySource.keys()].sort(byText)) {
    const { shards, licenses } = bySource.get(src);
    const dir = dirs.find((d) => src === d || src.startsWith(`${d}-`));
    const info = dir && existsSync(join(sourcesDir, dir, 'SOURCE.md')) ? readSource(readFileSync(join(sourcesDir, dir, 'SOURCE.md'), 'utf8')) : {};
    const worlds = uniqSorted(shards.map((s) => s.id.split('/')[0]));
    lines.push(`## ${src}`, '');
    if (info.what) lines.push(`- What: ${info.what}`);
    if (info.origin) lines.push(`- Origin: ${info.origin}`);
    lines.push(`- License: ${info.license ?? [...licenses].sort(byText).join(', ')}`);
    if (info.attribution) lines.push(`- Attribution: ${info.attribution}`);
    lines.push(`- Shard terms: ${[...licenses].sort(byText).join(', ')}`);
    lines.push(`- Used by: ${worlds.map((w) => `\`${w}\` (${shards.filter((s) => s.id.startsWith(`${w}/`)).length} shards)`).join(', ')}`, '');
  }
  return lines.join('\n');
}

export function buildCatalog(root = WORLDS_DIR, sourcesDir = join(REPO, 'sources')) {
  const v = validateWorlds(root);
  if (!v.ok) return { errors: v.errors };
  const { worlds, results } = v;
  // KR1 item 6 (review 2026-11-15, finding 2): the folders of data files that are not SOP (the TSV dictionaries of
  // w.lang.en and w.lang.ro) are catalogued with their sources and licence, one entry per folder (one licence each).
  const dataOf = new Map();
  for (const d of dataFolders(root)) {
    const head = d.files[0].header;
    const srcText = (head.sources ?? head.source ?? []).join('; ');
    const entry = { id: d.id, path: d.path, format: 'tsv', files: d.files.length, bytes: d.files.reduce((a, f) => a + f.bytes, 0),
      sources: uniqSorted(srcText.replace(/\([^)]*\)/g, '').split(';').map((x) => x.trim()).filter(Boolean).map(sourceId)), license: head.license?.[0] ?? null };
    if (!dataOf.has(d.world)) dataOf.set(d.world, []);
    dataOf.get(d.world).push(entry);
  }
  const vocab = new Map();
  // Block 07:40 item 3: what each word names: the type of the thing whose identity value it is (back: k.geo.river), the
  // type whose name a `core.word` gives another word for (Peking: k.geo.city), or the type or key a word of a schema
  // means (capital: k.geo.country.capital); a reusable world's words name the world (w.seating).
  const kinds = new Map();
  // Reviewer 04:10 item 4: a shard reached by a word only through facts whose reading needs a context (a given name
  // with `context=person`: Rose, Hope; a keyword, Q67) is listed after the word's other shards, so a host that fetches the first
  // shards of a word fetches the common word's first; the rest of each list stays sorted.
  const plain = new Map();
  const addWord = (word, shardId, kind, needsContext = false) => {
    if (!isWordy(word)) return;
    const k = lemma(word);
    if (!vocab.has(k)) vocab.set(k, new Set());
    vocab.get(k).add(shardId);
    if (!needsContext) { if (!plain.has(k)) plain.set(k, new Set()); plain.get(k).add(shardId); }
    if (!kind) return;
    if (!kinds.has(k)) kinds.set(k, new Map());
    const byKind = kinds.get(k);
    if (!byKind.has(kind)) byKind.set(kind, new Set());
    byKind.get(kind).add(shardId);
  };
  // the type of a slot id (k.geo.city.name -> k.geo.city); a word with no `of` means a type or a key itself
  const typeOfSlot = (slot) => slot.slice(0, slot.lastIndexOf('.'));
  const kindOfWord = (w) => (w.attrs.of?.[0] ? typeOfSlot(w.attrs.of[0]) : text(w.attrs.means?.[0] ?? '') || null);
  const entries = [];
  for (const world of worlds) {
    const info = moduleInfo(world.schemaText) ?? { name: world.id, version: null, imports: [], exports: [] };
    const { world: sw } = schemaWorld(worlds, world.id);
    const idKeys = new Map();
    const identityKeys = (type) => {
      if (!idKeys.has(type)) {
        const s = sw.schema(type);
        idKeys.set(type, s ? Object.entries(s.keys).filter(([, k]) => k.id).map(([name]) => name) : []);
      }
      return idKeys.get(type);
    };
    const shardWires = new Map();
    const shards = world.shards.map((shard) => {
      const wires = parse(shard.text);
      shardWires.set(shard.id, wires);
      const header = readHeader(shard.text);
      const keys = [];
      for (const w of wires) {
        if (w.type === 'core.word') {
          // the words of another world, in its language world's shard words-<world> (Q78): read below as that world's own
          if (!worldOfWordsShard(shard.id)) for (const t of w.attrs.text ?? []) addWord(text(t), shard.id, kindOfWord(w));
          continue;
        }
        if (SEARCH_KEYS.has(w.type)) for (const t of w.attrs[SEARCH_KEYS.get(w.type)] ?? []) addWord(text(t), shard.id, w.type, true);
        // a reusable world of facts (w.lang.en) names its own parts (frames, constructions, categories): only the
        // keys that hold English words make vocabulary
        for (const k of identityKeys(w.type).filter((x) => !world.id.startsWith('w.') || WORD_KEYS.has(x))) for (const t of w.attrs[k] ?? []) {
          const x = text(t);
          if (isWordy(x) && !PLACEHOLDER.test(x)) { keys.push(lemma(x)); addWord(x, shard.id, w.type, Boolean(w.attrs.context?.includes('person'))); }
        }
        if (!world.id.startsWith('w.')) for (const k of THING_KEYS) if (!identityKeys(w.type).includes(k)) for (const t of w.attrs[k] ?? []) {
          const x = text(t);
          if (isWordy(x)) addWord(x, shard.id, `${w.type}.${k}`);
        }
      }
      const license = header.license?.[0] ?? null;
      const r = results.find((x) => x.shard === shard.id);
      const entry = {
        id: shard.id, path: shard.path, wires: wires.length, bytes: shard.bytes, keys: uniqSorted(keys),
        sources: uniqSorted(wires.flatMap((w) => (w.attrs['core.source'] ?? []).map(sourceId))),
        license,
      };
      entry.warnings = r.warnings;
      return entry;
    });
    // Words of the schema: a word for a value goes to the shards holding that value under that key; a word for a
    // type or a key of the world goes to the world's schema path (the host then knows the world is relevant and
    // picks its shards by the other words of the message).
    // (and the words of the world in the shards words-<world> of the language worlds, Q78: read exactly as schema words)
    const wordsShards = worlds.flatMap((x) => x.shards).filter((sh) => worldOfWordsShard(sh.id) === world.id);
    for (const w of [...parse(world.schemaText), ...wordsShards.flatMap((sh) => parse(sh.text))]) {
      if (w.type !== 'core.word') continue;
      const means = text(w.attrs.means?.[0] ?? '');
      const of = w.attrs.of?.[0];
      const targets = of
        ? world.shards.filter((s) => shardWires.get(s.id).some((x) => (x.attrs[of.slice(of.lastIndexOf('.') + 1)] ?? []).some((t) => text(t) === means))).map((s) => s.id)
        : [world.schemaPath];
      for (const t of w.attrs.text ?? []) for (const id of targets) addWord(text(t), id, kindOfWord(w));
    }
    entries.push({
      id: world.id,
      version: info.version ?? null,
      schema: world.schemaPath,
      exports: uniqSorted(info.exports),
      depends: uniqSorted(info.imports),
      shards,
      sources: uniqSorted([...shards, ...(dataOf.get(world.id) ?? [])].flatMap((s) => s.sources)),
      licenses: uniqSorted([...shards, ...(dataOf.get(world.id) ?? [])].map((s) => s.license).filter(Boolean)),
      ...(dataOf.has(world.id) ? { data: dataOf.get(world.id) } : {}),
      warnings: results.find((x) => x.world === world.id && x.shard === null)?.warnings ?? [],
    });
  }
  // The reusable worlds (w.*): found by name. Their words go to the vocabulary with the path of the schema.
  const schemas = [];
  const allSchemas = scanSchemas(root);
  for (const s of allSchemas) {
    const d = describeSchema(s, allSchemas);
    if (d.errors.length) return { errors: d.errors };
    for (const t of d.allWords) addWord(t, s.schemaPath, d.entry.id ?? d.entry.name ?? null);
    schemas.push(d.entry);
  }
  const index = { version: contentVersion(root), sopworld: SOPWORLD, worlds: entries };
  if (schemas.length) index.schemas = schemas;
  const last = (k) => (id) => (plain.get(k)?.has(id) ? 0 : 1); // shards reached only through a reading that needs a context
  const vocabObj = Object.fromEntries([...vocab.keys()].sort(byText).map((k) => [k, [...vocab.get(k)].sort((a, b) => last(k)(a) - last(k)(b) || byText(a, b))]));
  const kindsObj = Object.fromEntries([...kinds.keys()].sort(byText).map((k) => [k, Object.fromEntries([...kinds.get(k).keys()].sort(byText).map((t) => [t, [...kinds.get(k).get(t)].sort(byText)]))]));
  return { errors: [], index, vocab: vocabObj, vocabKinds: kindsObj, licenses: licensesText(index, sourcesDir) };
}

export const serialize = (obj) => `${JSON.stringify(obj, null, 1)}\n`;
// one line per word (vocab-kinds.json would be three times the size of vocab.json with one line per value)
export const serializeCompact = (obj) => `{\n${Object.entries(obj).map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`).join(',\n')}\n}\n`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes('--check');
  const root = process.argv.slice(2).find((a) => !a.startsWith('--')) ?? WORLDS_DIR;
  const { errors, index, vocab, vocabKinds, licenses } = buildCatalog(root);
  if (errors.length) {
    for (const e of errors) console.error(`error: ${e}`);
    process.exit(1);
  }
  const files = { 'index.json': serialize(index), 'vocab.json': serialize(vocab), 'vocab-kinds.json': serializeCompact(vocabKinds), 'LICENSES.md': licenses };
  let stale = false;
  for (const [name, content] of Object.entries(files)) {
    const p = join(root, name);
    let old = null;
    try { old = readFileSync(p, 'utf8'); } catch {}
    if (old === content) continue;
    if (check) { console.error(`stale: ${name}`); stale = true; } else writeFileSync(p, content);
  }
  const shards = index.worlds.reduce((n, w) => n + w.shards.length, 0);
  console.log(`${index.worlds.length} worlds, ${shards} shards, ${Object.keys(vocab).length} words, version ${index.version}`);
  process.exit(stale ? 1 : 0);
}
