// The files that tools write and nobody edits by hand (block "Reviewer 2026-11-15 15:15"): they conflicted on every
// rebase (index.json, vocab.json, JOINS-REPORT.md, COVERAGE.md, the derived and relation shards ...). They stay in git,
// because GitHub Pages serves docs/ from the branch as it is and there is no build before publishing, but they never
// need a merge: `.gitattributes` gives them the merge driver `regenerate`, which keeps main's side (tools/sync.sh
// configures it in each clone: `git config merge.regenerate.driver true`), and tools/sync.sh then runs
// `npm run regenerate` on the rebased tip and puts the result into the worker's last commit. The append-only logs
// (worker-log.md, questions.md, worker-tasks.md, docs/lessons.md, CHANGELOG.md) take git's built-in `union` merge.
// Every other file is hand-written: a conflict in it stops tools/sync.sh, which never chooses a side for it.
//   node tools/generated.mjs           rewrites the block of .gitattributes between the markers
// A shard is generated when its header names as script a tool that `npm run regenerate` runs.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { REPO, WORLDS_DIR, scanWorlds, readHeader } from './lib/worlds.mjs';

export const ATTRIBUTES = join(REPO, '.gitattributes');
export const BEGIN = '# ---- generated by tools/generated.mjs: do not edit between the markers ----';
export const END = '# ---- end of the generated block ----';
export const LOGS = ['worker-log.md', 'questions.md', 'worker-tasks.md', 'docs/lessons.md', 'CHANGELOG.md'];
// Files and folders the regenerating tools write that are not shards with a `# script:` header.
export const OUTPUTS = ['docs/worlds/index.json', 'docs/worlds/vocab.json', 'docs/worlds/vocab-kinds.json', 'docs/worlds/LICENSES.md',
  'docs/worlds/JOINS.md', 'docs/worlds/COVERAGE.md', 'docs/worlds/k.attributes/ASPECTS.md', 'docs/worlds/k.kinds/JOINS-REPORT.md', 'docs/worlds/k.kinds/PARENTS.md',
  'docs/worlds/k.objects/preview/**', 'docs/worlds/k.scenes/preview/**', 'docs/worlds/w.lang.en/dictionary/*.tsv'];

// The tools `npm run regenerate` runs (from package.json, so a new build step counts at once).
export function regeneratingTools(pkg = JSON.parse(readFileSync(join(REPO, 'package.json'), 'utf8'))) {
  const s = `${pkg.scripts.regenerate ?? ''} ${pkg.scripts.build ?? ''}`;
  return [...new Set(s.match(/tools\/[\w.-]+\.mjs/g) ?? [])].sort();
}

export function generatedPaths(worlds = scanWorlds(), tools = regeneratingTools()) {
  const shards = [];
  for (const w of worlds) for (const s of w.shards) if (tools.includes(readHeader(s.text).script?.[0])) shards.push(relative(REPO, s.file).split('\\').join('/'));
  return [...OUTPUTS, ...shards.sort()];
}

export function attributesText(paths = generatedPaths(), old = existsSync(ATTRIBUTES) ? readFileSync(ATTRIBUTES, 'utf8') : '') {
  const block = [BEGIN, ...LOGS.map((f) => `${f} merge=union`), ...paths.map((p) => `${p} merge=regenerate`), END].join('\n');
  const i = old.indexOf(BEGIN), j = old.indexOf(END);
  const head = i < 0 ? `${old.trim() ? `${old.trimEnd()}\n\n` : ''}` : old.slice(0, i);
  const tail = j < 0 ? '' : old.slice(j + END.length).replace(/^\n/, '');
  return `${head}${block}\n${tail}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = attributesText();
  writeFileSync(ATTRIBUTES, text);
  console.log(`.gitattributes: ${text.split('\n').filter((l) => l.endsWith('merge=regenerate')).length} generated paths, ${LOGS.length} logs`);
}
