// Verb forms, plurals and degrees have one home, w.lang.en (reviewer blocks 14:45 and 16:45, KR2 item 4): the form
// words that k.words (WordNet's exception lists, `core.word … of=k.words.sense.word`) and k.actions (third person, past,
// -ing of each action) still carry are checked one by one with the pinned library: a form is confirmed when std.morph
// reads it back to its lemma with the w.lang.en dictionary (`analyse`), or `inflectBy` writes it from the lemma. A
// confirmed form is dropped from k.words / k.actions (w.lang.en has it); a form neither confirms stays where it is and
// is listed in docs/worlds/w.lang.en/FORMS-REPORT.md by its lemma's class.
//   node tools/forms-report.mjs            writes the report
//   node tools/forms-report.mjs --apply    also drops the confirmed forms from the k.words shards
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fullWorld, WORLDS_DIR } from './lib/worlds.mjs';
import { morphOf, analyse, dictionary, inflectBy } from './sopworld/sopworld.mjs';
import { TYPES, DIR } from './lang-en-morph.mjs';

const OPS = ['plural', 'third', 'past', 'ing', 'comparative', 'superlative'];
const KW = join(WORLDS_DIR, 'k.words', 'shards');
const FORMS = /^(@k\.words\.\S+\.forms core\.word )(.*?)( means=("[^"]*"|\S+) of=k\.words\.sense\.word.*)$/;
const unq = (t) => t.replace(/^"|"$/g, '');

// A checker over the pinned library: (lemma, form) -> confirmed?
export function formChecker() {
  const world = fullWorld('w.lang.en');
  const m = morphOf(world, { types: TYPES });
  const file = (p) => (existsSync(join(DIR, 'dictionary', `${p}.tsv`)) ? readFileSync(join(DIR, 'dictionary', `${p}.tsv`), 'utf8') : null);
  const dict = dictionary({ read: file });
  const check = (lemma, form) => analyse(m, form, { dictionary: dict }).some((r) => r.lemma === lemma)
    || OPS.some((op) => { try { return inflectBy(world, lemma, op) === form; } catch { return false; } });
  check.classOf = (lemma) => dict.lookup(lemma)?.class ?? '(no class)';
  return check;
}

// The form words of k.words: [{ file, line, lemma, forms: [text] }]
export function kwordsForms() {
  const out = [];
  for (const f of readdirSync(KW).filter((x) => x.endsWith('.sop')).sort()) readFileSync(join(KW, f), 'utf8').split('\n').forEach((l, i) => {
    const m = FORMS.exec(l);
    if (m) out.push({ file: f, line: i, lemma: unq(m[4]), forms: [...m[2].matchAll(/text=("[^"]*"|\S+)/g)].map((x) => unq(x[1])) });
  });
  return out;
}

export function report(check = formChecker()) {
  const rows = kwordsForms();
  const kept = [];
  let all = 0, confirmed = 0;
  for (const r of rows) for (const f of r.forms) { all += 1; if (check(r.lemma, f)) confirmed += 1; else kept.push([check.classOf(r.lemma), r.lemma, f]); }
  const byClass = new Map();
  for (const [c, l, f] of kept.sort((a, b) => (a[0] + a[1] < b[0] + b[1] ? -1 : 1))) (byClass.get(c) ?? byClass.set(c, []).get(c)).push(`${l} ${f}`);
  const text = `# Form words outside w.lang.en, checked with the pinned library

Generated by \`tools/forms-report.mjs\` (KR2 item 4, reviewer 16:45). Every form word of k.words (WordNet's exception
lists: went, mice, bigger …) is checked with the pinned sopworld: confirmed when std.morph reads it back to its lemma
with the w.lang.en dictionary (\`analyse\`) or \`inflectBy\` writes it from the lemma. Confirmed forms are dropped from
k.words (w.lang.en is their home); the others stay in k.words and are listed here by the class of their lemma in the
w.lang.en dictionary, for a decision each (an archaic or British variant to add to w.lang.en as a read-only
irregular form, or a WordNet entry that is no form of that lemma: cola is no plural of colon).

- form words left in k.words: ${all}, of which the library confirms ${confirmed} (each confirmed one is dropped by
  \`--apply\`; 1,459 of the 1,507 WordNet form words were dropped so, reviewer 16:45); listed here: ${kept.length}.
- k.actions keeps only the forms w.lang.en does not confirm (the hand-written actions shards: wetted).

${[...byClass].map(([c, xs]) => `## ${c} (${xs.length})\n\n${xs.join(', ')}\n`).join('\n')}`;
  return { text, all, confirmed, kept, rows };
}

// k.words shards with the confirmed forms dropped (a wire whose forms are all confirmed goes)
export function applied(check, rows = kwordsForms()) {
  const byFile = new Map();
  for (const r of rows) (byFile.get(r.file) ?? byFile.set(r.file, []).get(r.file)).push(r);
  const files = {};
  for (const [f, rs] of byFile) {
    const lines = readFileSync(join(KW, f), 'utf8').split('\n');
    for (const r of rs) {
      const m = FORMS.exec(lines[r.line]);
      const keep = r.forms.filter((x) => !check(r.lemma, x));
      lines[r.line] = keep.length ? `${m[1]}${keep.map((x) => `text=${/[\s"]/.test(x) ? JSON.stringify(x) : x}`).join(' ')}${m[3]}` : null;
    }
    files[f] = lines.filter((l) => l !== null).join('\n');
  }
  return files;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = formChecker();
  const r = report(check);
  writeFileSync(join(WORLDS_DIR, 'w.lang.en', 'FORMS-REPORT.md'), r.text);
  console.log(`forms: ${r.all} checked, ${r.confirmed} confirmed, ${r.kept.length} kept`);
  if (process.argv.includes('--apply')) {
    const files = applied(check, r.rows);
    for (const [f, t] of Object.entries(files)) writeFileSync(join(KW, f), t);
    console.log(`k.words: ${Object.keys(files).length} shards rewritten`);
  }
}
